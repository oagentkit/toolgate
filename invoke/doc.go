// Package invoke 提供不可绕过的工具调用链：门禁链由构造保证，而不是由调用点的自觉保证。
//
// # 为什么要有这个包
//
// 本仓既有的三包都只能**加**约束，没有一个能**强制**约束：
//
//   - policy.AuditGate 是装饰器——宿主忘了包一层，这次调用就没有审计门；
//   - toolsched 做的是调度与去重，不参与判定；
//   - toolprior 是优先级表，同样是数据不是闸。
//
// 「宿主忘了包」是个非常现实的失效形态：它不报错、不告警，工具照常执行，
// 事后从日志里也看不出这次调用没走审计门。OpenCode 2.0 上线一周内爆出的三个
// 安全回归（配置热重载窗口绕过 provider deny、系统级配置目录被静默丢弃、
// TUI 层 sandbox 在工具执行搬进后台服务后静默失效）全部属于同一形态：
// **信任边界移动了，沙箱没跟着移动**，而且静默。
//
// 所以本包的立论是：把门禁从「装饰」改成「结构」。
//
// # 结构在哪
//
// NewChain 把 Handler **按值收进私有字段**，此后不再对外暴露。于是：
//
//   - 想执行一次调用，唯一的办法就是 chain.Do，它必然过完整条链；
//   - 宿主无法拿到裸 Handler 再绕过链去调——那个函数值已经被链吞掉了；
//   - 链不可变（构造后 stages 只读），并发下多个调用共享同一条链没有竞态。
//
// 这条不变量是**类型层面**的，不是约定层面的：绕过代码写不出来。
//
// # 与审计面的一致性
//
// 一次调用无论结局是放行、拒绝、阶段报错还是 panic，Do 都**恰好**产出一条 Record。
// 这条同样重要：本仓此前存在审计面不对称——经 Code Mode 的调用有完整调用账目，
// 普通调用没有对等物。能力更强的路径审计更好，会让人在评审时高估整体覆盖。
//
// # fail-closed
//
// 构造期与执行期都偏向拒绝：
//
//   - NewChain(nil handler) 直接构造失败，不返回一个「空转」的链；
//   - 空工具名按拒绝处理（门禁不该对空名乐观放行）；
//   - Stage 返回 error 时按拒绝处理，不是按「跳过该环」处理；
//   - Stage 或 Handler panic 时被 recover 并转成错误，不杀编排进程。
